const express = require("express");
const router = express.Router();
const { registerUser, loginUser, getUserProfile, updateUserProfile, sendOtp, getSavedPlaces, addSavedPlace, updateSavedPlace, deleteSavedPlace, deleteOwnAccount } = require("../controllers/authController");
const { protect } = require("../middleware/authMiddleware");
router.post("/register", registerUser);
router.post("/login", loginUser);
router.post("/send-otp", sendOtp);
router.get("/profile", protect, getUserProfile);
router.put("/profile", protect, updateUserProfile);
router.delete("/profile", protect, deleteOwnAccount);
router.get("/places", protect, getSavedPlaces);
router.post("/places", protect, addSavedPlace);
router.put("/places/:index", protect, updateSavedPlace);
router.delete("/places/:index", protect, deleteSavedPlace);
module.exports = router;
